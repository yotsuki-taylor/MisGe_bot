"""Препараты, на которых общий подбор написания промахивается.

Транслитерация угадывает латинское написание по буквам и ранжирует варианты по
тому, что встречается чаще: «и» — это `i`, а `y` на её месте считается экзотикой
(см. цены замен в translit.py). Для «зиртек» это даёт `zirtec`, `zirtek`,
`zirthec`, `zirthek` — и только пятым вариантом настоящее `zyrtec`. Пять
обращений к сайту при лимите в один запрос в секунду — это пять секунд ожидания,
и все они впустую.

Поэтому здесь список того, о чём нам известно больше, чем можно вывести из букв.
Известное написание пробуется первым. Если у бренда знаем ещё и МНН, вторым идёт
поиск по нему: он находит аналоги, когда самого бренда в аптеках нет.

Список ведётся руками и пополняется по мере находок — добавить строчку дешевле,
чем чинить ранжирование ради одного препарата.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Dict, Optional, Tuple


@dataclass(frozen=True)
class Brand:
    """Что мы знаем про препарат сверх его русского названия."""

    names: Tuple[str, ...]
    """Латинские написания, в порядке правдоподобия."""

    generic: str = ""
    """МНН латиницей. Пустой — искать по МНН не будем.

    Пишется без хвоста, который расходится между источниками: сайт ищет по началу
    строки, поэтому `cetirizin` находит и «cetirizine», а `cetirizine` нашло бы
    только точное написание.
    """


KNOWN: Dict[str, Brand] = {
    # Zyrtec: «и» здесь пишется через y, чего побуквенный подбор не ждёт.
    "зиртек": Brand(names=("zyrtec",), generic="cetirizin"),
    # То же название по-грузински: ключи ведём для каждого алфавита, на котором
    # препарат могут спросить, — подбор промахивается одинаково с обоих.
    "ზირტეკი": Brand(names=("zyrtec",), generic="cetirizin"),
}

_SPACES = re.compile(r"\s+")


def lookup(text: str) -> Optional[Brand]:
    """Что известно про это название. None — ничего, работает общий подбор."""
    return KNOWN.get(normalise(text))


def normalise(text: str) -> str:
    """Ключ словаря: без регистра, лишних пробелов и разницы «ё»/«е»."""
    text = _SPACES.sub(" ", text.strip().lower()).replace("ё", "е")
    return text
