def ka_to_latin_candidates(text: str, limit: int = MAX_CANDIDATES) -> List[str]:
    """Ранжированные латинские написания грузинского названия.

    Падежное окончание отбрасывается: с ним не нашлось бы ничего.
    """
    return _candidates(strip_ka_ending(text), _ka_options, limit)


def strip_ka_ending(text: str) -> str:
    """Убрать грузинские окончания — именительное «-ი» и родительное «-ის».

    По каждому слову отдельно: в «ვიტამინი c» окончание у первого слова, и
    отбросив его только в конце строки, мы бы искали «vitamini c».
    """
    return _KA_WORD_RE.sub(lambda match: _strip_one_ending(match.group(0)), text.strip())


def _strip_one_ending(word: str) -> str:
    for ending in _KA_ENDINGS:
        if len(word) > len(ending) + 2 and word.endswith(ending):
            return word[:-len(ending)]
    return word


def _ka_options(text: str, position: int) -> Tuple[Sequence[Option], int]:
    """Варианты латинской записи для буквы и сколько букв съели."""
    char = text[position]
    following = text[position + 1] if position + 1 < len(text) else ""

    if char in ("კ", "ქ"):
        # «ქს» — это латинское x: ექსპრესი → express, ამოქსიცილინი → amoxicillin
        if following == "ს":
            return (("x", 0), ("ks", 1), ("cs", 3)), 2
        # «ce», «ci» читались бы как «це», «ци» — перед ними остаётся только k
        if following and following in _KA_FRONT_VOWELS:
            return (("k", 0), ("q", 3)), 1
        return (("c", 0), ("k", 1), ("q", 3)), 1

    if char == "ც":
        # Перед e/i латинская c и так звучит как «ц»: citramon, cefazolin
        if following and following in _KA_FRONT_VOWELS:
            return (("c", 0), ("ts", 2)), 1
        return (("ts", 0), ("c", 1), ("z", 2)), 1

    if char == "ხ":
        # В начале слова перед согласной это почти всегда греческое ch-:
        # ხლორი → chlor. В середине слова — скорее h.
        if position == 0 and following and following not in _KA_VOWELS:
            return (("ch", 0), ("h", 1), ("kh", 2), ("x", 3)), 1
        return (("kh", 0), ("h", 1), ("ch", 1), ("x", 2)), 1

    options = _KA_TO_LAT_SEARCH.get(char)
    if options is None:
        return ((char, 0),), 1
    return options, 1


