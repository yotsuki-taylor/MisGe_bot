"""Транслитерация в обе стороны.

Направлений два, и они устроены по-разному.

**Наружу, грузиница → кириллица.** Однозначная замена по алфавиту: 33 буквы,
каждой соответствует своя. Нужна, чтобы показать пользователю название препарата
и адрес аптеки — весь контент mis.ge на грузинском.

**Внутрь, кириллица и грузиница → латиница.** Здесь однозначного ответа нет. Сайт
ищет не по грузинскому написанию, а по международному латинскому названию
препарата, причём по началу строки и минимум от трёх букв. Русские названия
лекарств — сами по себе транслитерация тех же латинских, но неоднозначная:
«диклофенак» это `diclofenac`, а «кетонал» — `ketonal`, хотя буква «к» одна и та
же. Поэтому функция отдаёт не один вариант, а ранжированный список кандидатов;
перебирать их — дело search.py.

Грузинский запрос идёт тем же путём, и это не лишнее звено: «ნუროფენი» сайт не
находит, а `nurofen` находит. Таблица для него своя, не та, которой мы пишем
названия аптек: там ფ — это `p` (национальная романизация, как на дорожных
знаках), а в названиях препаратов та же буква передаёт заимствованное `f`.
Плюс отбрасывается падежное окончание: в базе сайта его нет.
"""

